const { contextBridge, ipcRenderer } = require('electron');
const inv = (ch, ...a) => ipcRenderer.invoke(ch, ...a);

contextBridge.exposeInMainWorld('nexApi', {
  on: (ch, fn) => ipcRenderer.on(ch, (_, d) => fn(d)),
  setIgnore: v => ipcRenderer.send('ignore', v),
  focus: () => ipcRenderer.send('focus'),
  ready: () => ipcRenderer.send('ready'),
  appsAdd: () => inv('apps-add'),
  appsOpen: id => inv('apps-open', id),
  setKey: k => inv('set-key', k),
  mailSend: (m, l) => inv('mail-send', m, l),
  mailVerify: c => inv('mail-verify', c),
  appsDel: id => inv('apps-del', id),
  getAll: () => inv('get-all'),
  saveProfile: p => inv('save-profile', p),
  saveSettings: s => inv('save-settings', s),
  saveTasks: d => inv('save-tasks', d),
  sys: (cmd, args) => inv('sys', cmd, args || {}),
  stats: () => inv('stats'),
  weather: () => inv('weather'),
  wallpaper: () => inv('wallpaper'),
  chat: t => inv('chat', t),
  stop: () => inv('stop'),
  newChat: () => inv('new-chat'),
  clipCopy: t => inv('clip-copy', t),
  remAdd: r => inv('rem-add', r),
  remDel: id => inv('rem-del', id),
  remList: () => inv('rem-list'),
  usage: () => inv('usage'),
  index: () => inv('index'),
  icon: p => inv('icon', p),
  openPath: p => inv('open-path', p),
  rates: () => inv('rates'),
  nightLight: () => inv('night-light'),
  citySuggest: q => inv('city-suggest', q),
  filesSearch: q => inv('files-search', q),
  translate: t => inv('translate', t),
  screenSource: () => inv('screen-source'),
  saveVideo: b => inv('save-video', b),
  clipPin: id => inv('clip-pin', id),
  clipDel: id => inv('clip-del', id),
  clipClear: () => inv('clip-clear'),
  screenshot: () => inv('screenshot'),
  showItem: p => inv('show-item', p),
  winSettings: page => inv('win-settings', page),
  openUrl: u => inv('open-url', u),
  google: () => inv('google'),
  googleReady: () => inv('google-ready'),
  cloudRestore: d => inv('cloud-restore', d),
  updateCheck: () => inv('update-check'),
  updateInstall: () => inv('update-install'),
  onUpdate: f => ipcRenderer.on('update', (_, d) => f(d)),
  onUpdateProgress: f => ipcRenderer.on('update-progress', (_, d) => f(d))
});
